// Pont entre l'interface et le processus principal.
// Seules les fonctions listées ici existent côté interface, sous `window.atelier`.

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('atelier', {
  openFolder: () => ipcRenderer.invoke('folder:open'),
  recentFolders: () => ipcRenderer.invoke('folder:recents'),
  openRecentFolder: (folder) => ipcRenderer.invoke('folder:openRecent', folder),
  setWindowTheme: (options) => ipcRenderer.invoke('window:theme', options),
  blurSupported: () => ipcRenderer.invoke('window:blurSupported'),
  relaunch: () => ipcRenderer.invoke('app:relaunch'),

  // Chat avec Claude
  claudeSend: (text) => ipcRenderer.invoke('claude:send', text),
  claudePermission: (answer) => ipcRenderer.invoke('claude:permission', answer),
  claudeInterrupt: () => ipcRenderer.invoke('claude:interrupt'),
  claudeReset: () => ipcRenderer.invoke('claude:reset'),
  claudeResume: (sessionId) => ipcRenderer.invoke('claude:resume', sessionId),
  claudeHistory: () => ipcRenderer.invoke('claude:history'),
  claudeHistoryGet: (id) => ipcRenderer.invoke('claude:history:get', id),
  claudeHistorySave: (conversation) => ipcRenderer.invoke('claude:history:save', conversation),
  claudeHistoryDelete: (id) => ipcRenderer.invoke('claude:history:delete', id),
  onClaudeEvent: (callback) => ipcRenderer.on('claude:event', (_event, e) => callback(e)),
  platform: process.platform,
  readFolder: (dir) => ipcRenderer.invoke('folder:read', dir),
  readFile: (file) => ipcRenderer.invoke('file:read', file),
  fileInfo: (file) => ipcRenderer.invoke('file:info', file),
  fileDataUrl: (file) => ipcRenderer.invoke('file:dataUrl', file),
  openDefault: (file) => ipcRenderer.invoke('file:openDefault', file),
  revealFile: (file) => ipcRenderer.invoke('file:reveal', file),
  writeFile: (file, content) => ipcRenderer.invoke('file:write', file, content),
  createFile: (file) => ipcRenderer.invoke('file:create', file),
  createFolder: (dir) => ipcRenderer.invoke('folder:create', dir),
  listFiles: () => ipcRenderer.invoke('files:list'),
  replaceText: (options, replace, extra) => ipcRenderer.invoke('search:replace', options, replace, extra),
  searchText: (options, texts) => ipcRenderer.invoke('search:text', options, texts),
  renamePath: (from, to) => ipcRenderer.invoke('path:rename', from, to),
  trashPath: (target) => ipcRenderer.invoke('path:trash', target),
  previewUrl: (file) => ipcRenderer.invoke('preview:url', file),
  previewExternal: (url) => ipcRenderer.invoke('preview:external', url),
  gitStatus: () => ipcRenderer.invoke('git:status'),
  // Nouveau projet (Vue, Vite, site HTML…)
  projectDefaults: () => ipcRenderer.invoke('project:defaults'),
  createProject: (request) => ipcRenderer.invoke('project:create', request),
  cancelProject: () => ipcRenderer.invoke('project:cancel'),
  onProjectLog: (callback) => ipcRenderer.on('project:log', (_event, entry) => callback(entry)),
  openLink: (url) => ipcRenderer.invoke('link:open', url),
  pickFolder: (defaultPath) => ipcRenderer.invoke('dialog:pickFolder', defaultPath),
  gitInit: () => ipcRenderer.invoke('git:init'),
  gitHead: (file) => ipcRenderer.invoke('git:head', file),
  gitStage: (files) => ipcRenderer.invoke('git:stage', files),
  gitUnstage: (files) => ipcRenderer.invoke('git:unstage', files),
  gitCommit: (message) => ipcRenderer.invoke('git:commit', message),
  gitPush: () => ipcRenderer.invoke('git:push'),
  gitPull: () => ipcRenderer.invoke('git:pull'),
  getSession: () => ipcRenderer.invoke('session:get'),
  saveSession: (session) => ipcRenderer.invoke('session:save', session),
  joinPath: (...parts) => ipcRenderer.invoke('path:join', ...parts),
  getConfig: () => ipcRenderer.invoke('config:get'),
  getConfigPath: () => ipcRenderer.invoke('config:path'),
  saveConfig: (changes) => ipcRenderer.invoke('config:save', changes),
  pauseShortcuts: (paused) => ipcRenderer.invoke('shortcuts:pause', paused),

  // Erreurs et raccourcis
  getLogPath: () => ipcRenderer.invoke('log:path'),
  log: (level, message) => ipcRenderer.send('log:write', level, message),
  onAppError: (callback) => ipcRenderer.on('app:error', (_event, message) => callback(message)),
  onFilesChanged: (callback) => ipcRenderer.on('fs:changed', (_event, files) => callback(files)),
  onShortcut: (callback) => ipcRenderer.on('shortcut', (_event, action) => callback(action)),

  // Mise à jour
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),

  // Terminaux
  createTerminal: (profileName, cols, rows, cwd) => ipcRenderer.invoke('term:create', profileName, cols, rows, cwd),
  writeTerminal: (id, data) => ipcRenderer.send('term:write', id, data),
  resizeTerminal: (id, cols, rows) => ipcRenderer.send('term:resize', id, cols, rows),
  killTerminal: (id) => ipcRenderer.send('term:kill', id),
  onTerminalData: (callback) => ipcRenderer.on('term:data', (_event, id, data) => callback(id, data)),
  onTerminalExit: (callback) => ipcRenderer.on('term:exit', (_event, id, code) => callback(id, code)),

  // Serveurs favoris
  listServers: () => ipcRenderer.invoke('servers:list'),
  saveServer: (server) => ipcRenderer.invoke('servers:save', server),
  deleteServer: (id) => ipcRenderer.invoke('servers:delete', id),
  pickKeyFile: () => ipcRenderer.invoke('dialog:pickKey'),
  // Intelligence Vue (Volar)
  vueOpen: (file, text) => ipcRenderer.invoke('vue:open', file, text),
  vueChange: (file, text) => ipcRenderer.invoke('vue:change', file, text),
  vueClose: (file) => ipcRenderer.invoke('vue:close', file),
  vueCompletion: (file, position, trigger) => ipcRenderer.invoke('vue:completion', file, position, trigger),
  vueResolve: (file, source, item, position) => ipcRenderer.invoke('vue:resolve', file, source, item, position),
  vueHover: (file, position) => ipcRenderer.invoke('vue:hover', file, position),
  vueSignature: (file, position) => ipcRenderer.invoke('vue:signature', file, position),
  vueDefinition: (file, position) => ipcRenderer.invoke('vue:definition', file, position),
  vueDiagnostics: (file) => ipcRenderer.invoke('vue:diagnostics', file),
  vueStop: () => ipcRenderer.invoke('vue:stop'),
  listScripts: () => ipcRenderer.invoke('scripts:list'),
  runScript: (dir, script, cols, rows) => ipcRenderer.invoke('term:script', dir, script, cols, rows),
  connectServer: (id, cols, rows) => ipcRenderer.invoke('term:connect', id, cols, rows),
});
